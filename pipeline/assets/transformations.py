"""dbt transformation assets.

Wraps the dbt project as Dagster assets so transformations
are observable, schedulable, and dependency-tracked.

The dbt manifest is generated by running `dbt compile` or `dbt build`.
If the manifest does not exist yet (e.g. fresh clone, CI before first dbt run),
the asset list is empty so imports don't fail.
"""

from pathlib import Path

from dagster import AssetExecutionContext
from dagster_dbt import DbtCliResource, dbt_assets

DBT_PROJECT_DIR = Path(__file__).resolve().parents[2] / "dbt"
DBT_MANIFEST = DBT_PROJECT_DIR / "target" / "manifest.json"


if DBT_MANIFEST.exists():
    @dbt_assets(manifest=DBT_MANIFEST)
    def scouter_dbt_assets(context: AssetExecutionContext, dbt: DbtCliResource) -> None:  # type: ignore[return]
        """Run all dbt models in the Scouter project.

        Args:
            context: Dagster asset execution context.
            dbt: Injected DbtCliResource.
        """
        yield from dbt.cli(["build"], context=context).stream()

    _dbt_assets_list = [scouter_dbt_assets]
else:
    _dbt_assets_list = []
